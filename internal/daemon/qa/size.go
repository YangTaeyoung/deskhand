package qa

import "fmt"

// byteSize writes n as the Mac app writes sizes: whole bytes under 1024,
// otherwise one decimal in the largest of GB, MB or KB (base 1024) that n
// reaches.
func byteSize(n int64) string {
	switch {
	case n >= 1<<30:
		return fmt.Sprintf("%.1f GB", float64(n)/(1<<30))
	case n >= 1<<20:
		return fmt.Sprintf("%.1f MB", float64(n)/(1<<20))
	case n >= 1<<10:
		return fmt.Sprintf("%.1f KB", float64(n)/(1<<10))
	}
	return fmt.Sprintf("%d B", n)
}
